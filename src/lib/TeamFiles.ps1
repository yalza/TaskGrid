# Files generated for every team launch (spec 4.3, 5.1, 7.1).

function Get-TeamContext($Config, [string]$RepoRoot) {
    $worktreeRoot = Get-WorktreeRoot $RepoRoot
    $members = @()
    foreach ($m in @($Config.members)) {
        $isMain = ($m.workspace -eq 'main')
        $workspace = Join-Path $worktreeRoot "$($Config.team)-$($m.name)"
        if ($isMain) { $workspace = $RepoRoot }
        $members += [pscustomobject]@{
            Name        = [string]$m.name
            SessionName = "$($Config.team)-$($m.name)"
            Agent       = [string]$m.agent
            Model       = [string]$m.model
            Effort      = [string]$m.effort
            Advisor     = [string]$m.advisor
            IsMain      = $isMain
            Workspace   = $workspace
            Branch      = "team/$($Config.team)-$($m.name)"
            Unity       = ($m.unity -eq $true)
            Readonly    = ($m.readonly -eq $true)
        }
    }
    $unityTools = @()
    if ($Config.unityTools) { $unityTools = @($Config.unityTools) }
    return [pscustomobject]@{
        Team           = [string]$Config.team
        RepoRoot       = $RepoRoot
        WorktreeRoot   = $worktreeRoot
        TeamDir        = (Join-Path $worktreeRoot '_team')
        PermissionMode = [string]$Config.permissionMode
        UnityTools     = $unityTools
        Members        = $members
    }
}

# Claude Code permission rules use POSIX paths; on Windows "E:\A\b" is written "//e/A/b".
function ConvertTo-RulePath([string]$Path) {
    $p = ($Path -replace '\\', '/').TrimEnd('/')
    if ($p -match '^([A-Za-z]):(.*)$') { $p = '//' + $Matches[1].ToLower() + $Matches[2] }
    return $p
}

# Only Read(...) and Edit(...) path rules are matched; Edit covers every file-editing tool.
function New-MemberSettings($Ctx, $Member) {
    $team = ConvertTo-RulePath $Ctx.TeamDir
    $allow = @("Read($team/**)", "Edit($team/**)")
    $deny = @()
    if (-not $Member.Unity) { $deny += @($Ctx.UnityTools) }
    if ($Member.Readonly) { $deny += "Edit($(ConvertTo-RulePath $Member.Workspace)/**)" }
    return [ordered]@{ permissions = [ordered]@{ allow = $allow; deny = $deny } }
}

function New-ProtocolText($Ctx, [string]$ProjectRules, [string]$TemplatePath) {
    $rows = @()
    $owner = $null
    foreach ($m in $Ctx.Members) {
        $model = $m.Model
        if ($m.Effort) { $model += ", effort $($m.Effort)" }
        if ($m.Advisor) { $model += ", advisor $($m.Advisor)" }
        $rows += "| ``$($m.SessionName)`` | $($m.Agent) | $model | ``$($m.Workspace)`` |"
        if ($m.Unity) { $owner = $m.SessionName }
    }
    $unityLine = 'No member owns the Unity Editor.'
    if ($owner) { $unityLine = "Unity Editor owner: ``$owner``. Only this member uses Unity Editor tools." }
    $rules = "$ProjectRules".Trim()
    if (-not $rules) { $rules = 'No project-specific rules. Follow the project CLAUDE.md.' }

    $text = [IO.File]::ReadAllText($TemplatePath)
    $text = $text.Replace('{{TEAM}}', $Ctx.Team).Replace('{{TEAM_DIR}}', $Ctx.TeamDir)
    $text = $text.Replace('{{ROSTER}}', ($rows -join "`n")).Replace('{{UNITY_OWNER}}', $unityLine)
    $text = $text.Replace('{{PROJECT_RULES}}', $rules)
    return ($text -replace "`r`n", "`n")
}

function New-LaunchScript($Ctx, $Member, [string]$SessionId, [bool]$Resume) {
    $a = @('--agent', $Member.Agent, '--model', $Member.Model)
    if ($Member.Effort) { $a += @('--effort', $Member.Effort) }
    if ($Member.Advisor) { $a += @('--advisor', $Member.Advisor) }
    $a += @('--name', $Member.SessionName)
    if ($Resume) { $a += @('--resume', $SessionId) } else { $a += @('--session-id', $SessionId) }
    if ($Ctx.PermissionMode) { $a += @('--permission-mode', $Ctx.PermissionMode) }
    $a += @('--add-dir', $Ctx.TeamDir,
            '--settings', (Join-Path $Ctx.TeamDir "settings\$($Member.Name).json"),
            '--append-system-prompt-file', (Join-Path $Ctx.TeamDir 'protocol.md'))
    $argList = ($a | ForEach-Object { ConvertTo-PsLiteral $_ }) -join ', '

    $lines = @(
        '# Generated by TaskGrid (grid team) on every launch. Do not edit.',
        ('Get-ChildItem Env: | Where-Object { $_.Name -match ' + (ConvertTo-PsLiteral $script:SessionEnvPattern) + ' } | ForEach-Object { Remove-Item (''Env:'' + $_.Name) }'),
        '$env:CLAUDE_CODE_EXPERIMENTAL_AGENT_TEAMS = ''0''',
        '$ErrorActionPreference = ''Stop''',
        ('Set-Location -LiteralPath ' + (ConvertTo-PsLiteral $Member.Workspace)),
        ('& claude @(' + $argList + ')')
    )
    return ($lines -join "`n") + "`n"
}

function Read-Sessions([string]$Path) {
    $map = @{}
    if (Test-Path -LiteralPath $Path) {
        $obj = Get-Content -Raw -LiteralPath $Path | ConvertFrom-Json
        foreach ($p in $obj.PSObject.Properties) {
            $map[$p.Name] = @{ Id = [string]$p.Value.id; ProtocolHash = [string]$p.Value.protocolHash }
        }
    }
    return $map
}

function Write-Sessions([string]$Path, [hashtable]$Map) {
    $o = [ordered]@{}
    foreach ($k in ($Map.Keys | Sort-Object)) {
        $o[$k] = [ordered]@{ id = $Map[$k].Id; protocolHash = $Map[$k].ProtocolHash }
    }
    Write-Utf8File $Path (($o | ConvertTo-Json -Depth 4) + "`n")
}

# Where Claude Code keeps a session's transcript: the workspace path with every character
# other than an ASCII letter or digit turned into '-'.
function Get-TranscriptPath([string]$Workspace, [string]$SessionId) {
    $folder = $Workspace -replace '[^A-Za-z0-9]', '-'
    return Join-Path $env:USERPROFILE ".claude\projects\$folder\$SessionId.jsonl"
}

# Which session id each member starts with, and what to warn about. $HasTranscript is
# { param($name, $id) -> bool }: a pane that never got a prompt has no transcript to resume.
function Get-ResumePlan([hashtable]$Sessions, [string[]]$Names, [string]$ProtocolHash, [bool]$Resume, [scriptblock]$HasTranscript = { $true }) {
    $entries = @{}
    $warnings = @()
    foreach ($n in $Names) {
        $saved = $Sessions[$n]
        if ($Resume -and $saved -and $saved.Id -and -not (& $HasTranscript $n $saved.Id)) {
            $warnings += "${n}: saved session has no transcript (it never got a prompt), starting a new one."
            $entries[$n] = @{ Id = [guid]::NewGuid().ToString(); Resume = $false }
        }
        elseif ($Resume -and $saved -and $saved.Id) {
            $entries[$n] = @{ Id = $saved.Id; Resume = $true }
            if ($saved.ProtocolHash -ne $ProtocolHash) {
                $warnings += "${n}: the protocol changed since this session started. Tell the PM: 'protocol changed, ask everyone to re-read protocol.md'."
            }
        }
        else {
            if ($Resume) { $warnings += "${n}: no saved session, starting a new one." }
            $entries[$n] = @{ Id = [guid]::NewGuid().ToString(); Resume = $false }
        }
    }
    return @{ Entries = $entries; Warnings = $warnings }
}
